// Execute application-owned actions through the selected CLI/MCP page.
async (page, request) => {
  // Keep hostname grants in the controlling runtime, outside website JavaScript.
  const context = page.context();
  // Refresh exact-host grants whenever an operation starts.
  context.__ibaAllowedHosts = Array.from(new Set([...(context.__ibaAllowedHosts || []), ...request.hosts]));
  // Compare common website sibling hosts without maintaining a site-specific list.
  const hostFamily = host => {
    // Keep localhost and IP addresses as exact boundaries.
    if (host === 'localhost' || /^\d{1,3}(?:\.\d{1,3}){3}$/.test(host)) return host;
    // Split ordinary DNS names into labels.
    const labels = String(host || '').toLowerCase().split('.').filter(Boolean);
    // One-label hosts remain exact.
    if (labels.length < 2) return labels.join('.');
    // Recognize common compound country-code suffixes conservatively.
    const compound = new Set(['co.uk','com.au','co.in','co.jp','com.br','com.sg','co.nz','co.za']);
    // Read the final two labels once.
    const suffix = labels.slice(-2).join('.');
    // Compound suffixes retain one registrable label.
    return compound.has(suffix) && labels.length >= 3 ? labels.slice(-3).join('.') : suffix;
  };
  // Apply exact explicit grants plus the selected website family.
  const allowed = url => {
    // Parse only browser-supplied or application-owned HTTP(S) destinations.
    const host = new URL(url).hostname.toLowerCase();
    // Accept an exact planned host or a sibling host in the selected site family.
    return context.__ibaAllowedHosts.includes(host) || !!request.site_family && hostFamily(host) === request.site_family;
  };
  // Install one navigation policy before opening the selected site.
  if (!context.__ibaGuard) {
    // Avoid duplicate interception handlers across observations.
    context.__ibaGuard = true;
    // Inspect top-level navigation while permitting ordinary image/style resources.
    await context.route('**/*', async route => {
      // Read the actual request generated by the browser.
      const navigation = route.request();
      // Normal resources do not grant permission to navigate to their hostnames.
      if (!navigation.isNavigationRequest()) return route.continue();
      // A popup's first request may precede frame creation; treat it as top-level.
      let embedded = false;
      // Existing child-frame resources remain allowed without granting navigation authority.
      try { embedded = !!navigation.frame().parentFrame(); } catch (_) { /* New popup has no frame yet. */ }
      // Only confirmed child-frame requests bypass the top-level hostname check.
      if (embedded) return route.continue();
      // Reject new hosts before issuing their navigation request.
      if (!allowed(navigation.url())) {
        // A recent grounded native click or direct navigation establishes bounded intent.
        const intendedNavigation = Date.now() <= (context.__ibaIntentUntil || 0);
        // Block unsolicited active-page redirects and advertising popups outside that intent window.
        if (!intendedNavigation) return route.abort('blockedbyclient');
        // Grant only this concrete autonomously planned destination host.
        context.__ibaAllowedHosts.push(new URL(navigation.url()).hostname.toLowerCase());
      }
      // Inspect redirects without automatically following them to another host.
      const response = await route.fetch({maxRedirects: 0});
      // Read Location before committing a redirect response.
      const destination = response.headers()['location'];
      // Apply the same exact-host policy to server redirects.
      if (destination && !allowed(new URL(destination, navigation.url()).href)) {
        // Preserve the same short intent interval for redirects and script-created pages.
        const intendedNavigation = Date.now() <= (context.__ibaIntentUntil || 0);
        // Reject unrelated or unsolicited redirects without interrupting the task.
        if (!intendedNavigation) return route.abort('blockedbyclient');
        // Authorize only the concrete redirect host for this current run.
        context.__ibaAllowedHosts.push(new URL(destination, navigation.url()).hostname.toLowerCase());
      }
      // Preserve the original document response and eligible session cookies.
      return route.fulfill({response});
    });
    // Dismiss ordinary dialogs without accepting consequential confirmations.
    page.on('dialog', dialog => dialog.dismiss());
    // Apply the same dialog behavior to newly opened pages.
    context.on('page', opened => opened.on('dialog', dialog => dialog.dismiss()));
  }
  // Read an intercepted destination independently of generic tool failures.
  if (request.kind === 'blocked') {
    // Copy the pending destination before clearing it.
    const url = context.__ibaBlocked || '';
    // Keep subsequent navigation events independent.
    context.__ibaBlocked = '';
    // Return typed authorization evidence.
    return {url};
  }
  // A guard-only call prepares the context without performing navigation.
  if (request.kind === 'guard') return {success: true};
  // Register the passive pointer before navigation so every replacement document receives it.
  if (request.kind === 'install_cursor') {
    // Wrap the version-controlled function as a self-executing document-start script.
    const source = '(' + request.value + ')()';
    // Apply the script automatically to future top-level documents and authorized pages.
    await context.addInitScript(source);
    // Install it immediately in the current about:blank or already loaded document.
    await page.evaluate(request.value);
    // Read current CSS viewport geometry without a second transport operation.
    const viewport = page.viewportSize() || {width:1280,height:800};
    // Move genuine browser input immediately so the current document displays the arrow.
    await page.mouse.move(viewport.width / 2,viewport.height / 2);
    // Report installation separately from pointer movement.
    return {success:true};
  }
  // Export cookies and eligible origin state only to the controlling runtime.
  if (request.kind === 'session_export') return await context.storageState();
  // Restore assistance state before navigation without logging credentials or cookies.
  if (request.kind === 'session_restore') {
    // Decode the runtime-owned transfer payload.
    const state = JSON.parse(request.value);
    // Browser-native cookie APIs preserve HttpOnly and session cookie properties.
    await context.addCookies(state.cookies || []);
    // Install only matching-origin storage before the site's own scripts execute.
    await context.addInitScript(state => {
      // Include the current document's local and session storage in the transfer.
      const entries = [...(state.origins || []), ...(state.current ? [state.current] : [])];
      // Never apply one hostname's storage to an unrelated destination.
      for (const entry of entries) if (entry.origin === location.origin) {
        // Preserve original local storage names and values exactly.
        for (const item of entry.localStorage || []) localStorage.setItem(item.name, item.value);
        // Session storage supports continuing the user's same logical run.
        for (const [name, value] of entry.sessionStorage || []) sessionStorage.setItem(name, value);
      }
    }, state);
    // Restoration is setup evidence, not a claim that authentication is still valid.
    return {success: true};
  }
  // Initialize the actual browser pointer for a new visible document, including read-only tasks.
  if (request.kind === 'pointer_start') {
    // Use current CSS viewport geometry rather than screenshot pixels or OS mouse coordinates.
    const viewport = page.viewportSize() || {width:1280,height:800};
    // Native movement triggers the passive marker without taking over the desktop pointer.
    await page.mouse.move(viewport.width / 2, viewport.height / 2, {steps:12});
    // Report native input, never an independently animated marker.
    return {success:true};
  }
  // Dispatch visible scrolling through the actual browser mouse and wheel.
  if (request.kind === 'wheel') {
    // Coordinates come from the current observed scroll container, never model guesses.
    const point = JSON.parse(request.value);
    // Move real native input to that container before scrolling it.
    await page.mouse.move(point.x, point.y, {steps:8});
    // Let the website receive genuine wheel input at that same pointer position.
    await page.mouse.wheel(0, point.delta);
    // Fresh source/measurements establish actual movement after rendering.
    return {success:true};
  }
  // Return current tabs from the actual context.
  if (request.kind === 'tabs') return context.pages().map((item, index) => ({index, id: String(index), url: item.url(), active: item === page}));
  // Authorize direct navigation before page.goto can issue a request.
  if (request.kind === 'navigate') {
    // Require an exact grant for the destination hostname.
    if (!allowed(request.target)) throw new Error('Hostname authorization required');
    // Bind redirect autonomy to this deliberate agent navigation for a bounded interval.
    context.__ibaIntentUntil = Date.now() + 5000;
    // Wait for document readiness without waiting for endless analytics traffic.
    await page.goto(request.target, {waitUntil: 'domcontentloaded', timeout: 20000});
    // Restore the genuine browser pointer immediately after the replacement document appears.
    if (request.headful) {
      try {
        await page.evaluate(() => {
          let cursor = document.getElementById('iba-cursor');
          if (!cursor) {
            cursor = document.createElement('div');
            cursor.id = 'iba-cursor';
            cursor.dataset.version = 'red-arrow-v3';
            cursor.setAttribute('aria-hidden', 'true');
            const x = Math.round((window.innerWidth || 1280) / 2);
            const y = Math.round((window.innerHeight || 800) / 2);
            window.__ibaPointer = { x, y };
            cursor.style.cssText = 'position:fixed !important;width:24px !important;height:32px !important;pointer-events:none !important;z-index:2147483647 !important;left:' + x + 'px;top:' + y + 'px;display:block !important;visibility:visible !important;margin:0 !important;transform:none !important;filter:drop-shadow(1px 1px 1px rgba(0,0,0,.55));';
            cursor.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="32" viewBox="0 0 24 32" aria-hidden="true"><path d="M1 1 L1 24 L7.5 18 L12.5 29 L17.5 26.7 L12.5 16.8 Z" fill="#ef2028" stroke="#ffffff" stroke-width="1.4" stroke-linejoin="round"/></svg>';
            document.documentElement.appendChild(cursor);
          } else {
            cursor.style.display = 'block';
            cursor.style.visibility = 'visible';
          }
        });
      } catch (_) {}
      // Use the stable viewport center until the next resolved action supplies exact target geometry.
      const viewport = page.viewportSize() || {width:1280,height:800};
      // Native movement updates the document-start arrow without moving the operating-system pointer.
      await page.mouse.move(viewport.width / 2, viewport.height / 2);
    }
    // Preserve the real resulting destination.
    return {success: true, url: page.url()};
  }
  // Escape the application-generated element token into a CSS attribute selector.
  const selector = '[data-iba-id=' + JSON.stringify(request.target) + ']';
  // Resolve the same native locator for pointer movement and input.
  const matches = [];
  // Include accessible frame contexts and open shadow roots supported by locators.
  for (const frame of page.frames()) {
    // Create a native locator instead of selecting an element by DOM position.
    const locator = frame.locator(selector);
    // Keep unique matches only; ambiguity is never resolved by guessing.
    if (await locator.count() === 1) matches.push(locator);
  }
  // A detached or duplicate identity requires another observation.
  if (matches.length !== 1) throw new Error('Target is stale or ambiguous');
  // Use one concrete native target for all remaining operations.
  const target = matches[0];
  // Reveal the actual target before inspecting its input coordinates.
  await target.scrollIntoViewIfNeeded({timeout: 5000});
  // Record geometry from that same unique native target.
  const box = await target.boundingBox();
  // Headful pointer movement follows a real native path to the resolved target.
  if (box && request.headful) {
    // Start from the last actual native mouse event, never an independent overlay position.
    const start = await page.evaluate(() => window.__ibaPointer || {x:0,y:0});
    // Keep visible motion short while giving the person time to follow the real pointer.
    for (let step=1; step<=8; step++) {
      // Move genuine browser input toward the same resolved native target center.
      await page.mouse.move(start.x + (box.x + box.width/2-start.x)*step/8, start.y + (box.y + box.height/2-start.y)*step/8);
      // Add only 128ms total in visible mode; headless interactions retain full speed.
      await new Promise(resolve => setTimeout(resolve,16));
    }
    // Show visual click effect at the target point.
    await page.evaluate(pt => { if (window.__ibaShowClickEffect) window.__ibaShowClickEffect(pt.x, pt.y); }, {x: box.x + box.width/2, y: box.y + box.height/2});
  }
  // Optional overlay closure avoids a redundant hover that can trigger or race another modal.
  const dismissal = request.kind === 'click' && request.value === '__iba_optional_overlay__';
  // Ordinary interactions retain explicit hover/actionability verification.
  if (!dismissal) await target.hover({timeout: 5000});
  // Send trusted browser input rather than calling DOM click().
  if (request.kind === 'click') {
    // Bind popup and redirect autonomy to this grounded native click briefly.
    context.__ibaIntentUntil = Date.now() + 2000;
    // Dispatch the trusted click after the intent boundary is installed.
    await target.click({timeout: dismissal ? 2000 : 5000});
  }
  // Native fill emits the input behavior expected by framework-controlled fields.
  else if (request.kind === 'fill') {
    // Click target first through pointer so cursor focuses input field visibly.
    await target.click({timeout: 5000});
    // Fill text into focused field.
    await target.fill(request.value, {timeout: 5000});
  }
  // Refuse unsupported actions instead of falling back to JavaScript mutation.
  else throw new Error('Unsupported native action');
  // A click may have replaced the document after its target received native input.
  if (request.kind === 'click' && request.headful) {
    // Re-dispatch at the resolved target point so the new document's init script becomes visible.
    await page.mouse.move(box ? box.x + box.width / 2 : 1, box ? box.y + box.height / 2 : 1);
  }
  // Report the identity and geometry actually used by input.
  return {success: true, target: request.target, box, url: page.url()};
}
